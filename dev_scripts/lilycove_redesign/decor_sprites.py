"""Turns map decorations (café umbrellas, table sets, market stalls...) into object-event
sprites, so they cost no city tiles. Called by build_lilycove.py with compose.DECOR.

For every art name it writes graphics/object_events/pics/misc/lc_<name>.png (tiles already in
OAM-piece order, 8 px wide strip), one shared palette, and src/data/object_events/lilycove_decor.h
(pics, subsprite tables, graphics infos). Constants/pointers live between LILYCOVE_DECOR markers.
The objects are (re)written at the end of data/maps/LilycoveCity/map.json.
"""
import os, json, re
from PIL import Image
import port_art

HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SLOT = 11                                      # all decorations are drawn in the market palette
VALID = {(8, 8), (16, 16), (32, 32), (64, 64), (16, 8), (32, 8), (32, 16), (64, 32), (8, 16), (8, 32), (16, 32), (32, 64)}
SHAPE = {(8, 8): 'SQUARE', (16, 16): 'SQUARE', (32, 32): 'SQUARE', (64, 64): 'SQUARE', (16, 8): 'H_RECTANGLE', (32, 8): 'H_RECTANGLE',
         (32, 16): 'H_RECTANGLE', (64, 32): 'H_RECTANGLE', (8, 16): 'V_RECTANGLE', (8, 32): 'V_RECTANGLE', (16, 32): 'V_RECTANGLE', (32, 64): 'V_RECTANGLE'}

def cname(name): return ''.join(p.capitalize() for p in name.split('_'))
def const(name): return 'OBJ_EVENT_GFX_LC_' + name.upper()

def pieces(w, h):
    def split(n, sizes):
        out, pos = [], 0
        for s in sizes:
            while n - pos >= s: out.append((pos, s)); pos += s
        return out
    out = []
    for (py, ph) in split(h, (32, 16)):
        for (px, pw) in split(w, (64, 32, 16)):
            if (pw, ph) in VALID: out.append((px, py, pw, ph))
            else:                                  # 64x16 -> two 32x16
                out += [(px, py, 32, ph), (px + 32, py, 32, ph)]
    return out

def build(decor):
    names = sorted({d[0] for d in decor})
    GROUPS = {11: ('lilycove_decor', 'LilycoveDecor', 'OBJ_EVENT_PAL_TAG_LILYCOVE_DECOR', port_art.PALETTES[11]),
              'hotel': ('lilycove_hotel', 'LilycoveHotel', 'OBJ_EVENT_PAL_TAG_LILYCOVE_HOTEL', None),
              'hall': ('lilycove_hall', 'LilycoveHall', 'OBJ_EVENT_PAL_TAG_LILYCOVE_HALL', None)}
    def group(n): return GROUPS[port_art.PAL_OF[n]]
    os.makedirs(os.path.join(REPO, 'graphics/object_events/palettes'), exist_ok=True)
    hdr = ['// Generated by dev_scripts/lilycove_redesign/decor_sprites.py -- do not edit.']
    for key, (fname, cname_, tag, p) in GROUPS.items():
        p = p if p is not None else port_art.OBJ_PALETTES[key]
        with open(os.path.join(REPO, 'graphics/object_events/palettes/%s.pal' % fname), 'w', newline='\r\n') as f:
            f.write('JASC-PAL\n0100\n16\n' + ''.join('%d %d %d\n' % tuple(c) for c in (list(p) + [(0, 0, 0)] * 16)[:16]))
        hdr.append('const u16 gObjectEventPal_%s[] = INCGFX_U16("graphics/object_events/palettes/%s.pal", ".gbapal");' % (cname_, fname))
    hdr.append('')
    info = {}
    for n in names:
        c = port_art.ART[n](); w, h = len(c[0]), len(c)
        ps = [p for p in pieces(w, h) if any(c[y][x] for y in range(p[1], p[1] + p[3]) for x in range(p[0], p[0] + p[2]))]
        tiles = []; subs = []
        for (px, py, pw, ph) in ps:
            subs.append((px, py, pw, ph, len(tiles)))
            for ty in range(ph // 8):
                for tx in range(pw // 8):
                    tiles.append([c[py + ty * 8 + y][px + tx * 8: px + tx * 8 + 8] for y in range(8)])
        g = group(n); pal = (list(g[3] if g[3] is not None else port_art.OBJ_PALETTES[port_art.PAL_OF[n]]) + [(0, 0, 0)] * 16)[:16]
        im = Image.new('P', (8, 8 * len(tiles))); im.putpalette([v for col in pal for v in col]); p = im.load()
        for i, t in enumerate(tiles):
            for y in range(8):
                for x in range(8): p[x, i * 8 + y] = t[y][x]
        im.save(os.path.join(REPO, 'graphics/object_events/pics/misc/lc_%s.png' % n))
        info[n] = (w, h, subs, len(tiles))
    UP = {}
    for (n, x, y, up) in decor: UP[n] = up
    for n in names:
        w, h, subs, nt = info[n]; C = cname(n); up = UP.get(n, 0)
        hdr.append('const u32 gObjectEventPic_Lc%s[] = INCGFX_U32("graphics/object_events/pics/misc/lc_%s.png", ".4bpp");' % (C, n))
        hdr.append('static const struct SpriteFrameImage sPicTable_Lc%s[] = { obj_frame_tiles(gObjectEventPic_Lc%s), };' % (C, C))
        tw = w // 16                                       # anchor: middle column, bottom row - anchor_up
        for prio in (2, 1):
            hdr.append('static const struct Subsprite sOamTable_Lc%s_%d[] = {' % (C, prio))
            for (px, py, pw, ph, off) in subs:
                x = px - (tw // 2) * 16 - 8; y = py - (h - up * 16 - 16 + 16 - h // 2)
                hdr.append('    {.x = %d, .y = %d, .shape = SPRITE_SHAPE(%dx%d), .size = SPRITE_SIZE(%dx%d), .tileOffset = %d, .priority = %d},'
                           % (x, y, pw, ph, pw, ph, off, prio))
            hdr.append('};')
        a, b = 'sOamTable_Lc%s_2' % C, 'sOamTable_Lc%s_1' % C
        hdr.append('static const struct SubspriteTable sOamTables_Lc%s[] = {' % C)
        for t in (a, a, b, a, b, b): hdr.append('    {ARRAY_COUNT(%s), %s},' % (t, t))
        hdr.append('};')
        hdr.append('''const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Lc%s = {
    .tileTag = TAG_NONE, .paletteTag = %s, .reflectionPaletteTag = OBJ_EVENT_PAL_TAG_NONE,
    .size = %d, .width = %d, .height = %d, .paletteSlot = PALSLOT_NPC_SPECIAL, .shadowSize = SHADOW_SIZE_M,
    .inanimate = TRUE, .compressed = FALSE, .tracks = TRACKS_NONE, .oam = &gObjectEventBaseOam_8x8,
    .subspriteTables = sOamTables_Lc%s, .anims = sAnimTable_Inanimate, .images = sPicTable_Lc%s,
};
''' % (C, group(n)[2], nt * 32, w, h, C, C))
    open(os.path.join(REPO, 'src/data/object_events/lilycove_decor.h'), 'w').write('\n'.join(hdr) + '\n')

    def block(path, begin, end, body):
        s = open(path).read(); i = s.index(begin) + len(begin); j = s.index(end)
        open(path, 'w').write(s[:i] + '\n' + body + s[j:])
    block(os.path.join(REPO, 'include/constants/event_objects.h'), '// LILYCOVE_DECOR_BEGIN', '    // LILYCOVE_DECOR_END',
          ''.join('    %s,\n' % const(n) for n in names))
    pp = os.path.join(REPO, 'src/data/object_events/object_event_graphics_info_pointers.h')
    block(pp, '// LILYCOVE_DECOR_EXTERN_BEGIN', '// LILYCOVE_DECOR_EXTERN_END',
          ''.join('extern const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Lc%s;\n' % cname(n) for n in names))
    block(pp, '    // LILYCOVE_DECOR_BEGIN', '    // LILYCOVE_DECOR_END',
          ''.join('    [%s] = &gObjectEventGraphicsInfo_Lc%s,\n' % (const(n), cname(n)) for n in names))

    # object events: drop the previous generated ones, append the new ones
    mp = os.path.join(REPO, 'data/maps/LilycoveCity/map.json'); m = json.load(open(mp))
    m['object_events'] = [e for e in m['object_events'] if not e['graphics_id'].startswith('OBJ_EVENT_GFX_LC_')]
    from compose import OX, OY
    for (n, x, y, up) in decor:
        w, h = info[n][0], info[n][1]
        m['object_events'].append({"graphics_id": const(n), "x": x + (w // 16) // 2 + OX, "y": y + h // 16 - 1 - up + OY,
            "elevation": 3, "movement_type": "MOVEMENT_TYPE_FACE_DOWN", "movement_range_x": 0, "movement_range_y": 0,
            "trainer_type": "TRAINER_TYPE_NONE", "trainer_sight_or_berry_tree_id": "0", "script": "0x0", "flag": "0"})
    open(mp, 'w').write(json.dumps(m, indent=2) + '\n')
    print('decor sprites: %d objects, %d graphics' % (len(decor), len(names)))
